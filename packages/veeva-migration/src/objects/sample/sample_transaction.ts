/**
 * `sample_transaction` — `Sample_Transaction_vod__c` → `sample_transaction__v`
 * (spec §6.3.35, §6.1 step 18, §6.2, §3.3, §4.4, §8.6).
 *
 * Regulated transactional rows (PDMA): scope is the OR of the per-type date
 * fields (`Call_Date`, `Transferred_Date`, `Adjusted_Date`, `Submitted_Date`,
 * `CreatedDate`) widened by `scope.sampleRetentionMonths` (family `samples`),
 * attributed to the owning rep's country with the account as fallback
 * (`['user:OwnerId', 'account']`), never deleted on the target (`ignore`).
 *
 * **Sample load strategy** (`objects.sample_transaction.load.sampleStrategy`,
 * per country; applies jointly to the whole samples family):
 *  - `noTriggersRecalc` (default): `noTriggers = true`, `state__v` submitted,
 *    then `postLoad.recalculateRollups` per touched `sample_lot__v` /
 *    `sample_inventory__v` (probe 17 — downgraded to `noTriggersVerify` with
 *    `SAMPLE_STRATEGY_DOWNGRADED` when the action is missing; blocking in the
 *    US overlay unless `fallbackStrategy` is named).
 *  - `noTriggersVerify`: no recalc; VQL roll-up verification per lot against
 *    the extracted `Calculated_Quantity_vod__c` (`sample_lot`) **and** the
 *    tool's recomputation Σ `signedQuantity(...)` of loaded submitted rows.
 *  - `triggersOnTransactions`: `noTriggers = false` here (`call2_sample` stays
 *    NoTriggers); trigger rejections are retried NoTriggers per batch
 *    (`load.sampleTriggerRejectFallback`, default true).
 *  - `triggersOnCallSamples`: disbursements are regenerated from
 *    `call2_sample`; this object is loaded for non-disbursement types only
 *    (`TRIGGERS_ON_CALL_SAMPLES_PREDICATE`).
 * The engine reads the strategy from `mapping.load`; the module only carries
 * the defaults and the pure helpers (`isDisbursement`, `signedQuantity`).
 *
 * `account__v` is optional except on disbursements (§6.3.35 "n (Y for
 * disbursement)") — `custom(accountRef)` enforces the conditional
 * requirement and otherwise behaves exactly like `ref(account)`.
 *
 * `Ref_Transaction_Id_vod__c` is a self reference patched in pass 2
 * (§6.1 step 18 `sample_transaction.ref_transaction_id__v`).
 *
 * Every target name is `[UNV]` (DOC object, fields by rename rule): preflight
 * validates and drops what the vault lacks. `State_vod__c` (address snapshot)
 * cannot be renamed mechanically — `state__v` is the lifecycle state — so it
 * targets `state_province__v` (the confirmed exception on address/em_event).
 */

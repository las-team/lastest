/** True when the row is a disbursement (record type first, `Type_vod__c` as fallback). */
export function isDisbursement(row: SourceRow): boolean {
  const rt = row["RecordType.DeveloperName"];
  if (typeof rt === "string" && rt.trim() !== "")
    return rt.trim() === SAMPLE_TRANSACTION_DISBURSEMENT_TYPE;
  const t = row["Type_vod__c"];
  return (
    typeof t === "string" && t.trim() === SAMPLE_TRANSACTION_DISBURSEMENT_TYPE
  );
}

/**
 * Sign of a submitted transaction's `quantity__v` in the lot roll-up
 * recomputation (§6.3.35 `noTriggersVerify`): receipt / transfer-in `+`,
 * disbursement / transfer-out / return `−`, adjustment `±` (the quantity
 * carries its own sign). `objectType` is the Vault object type api name
 * (`receipt__v`, …) or the SFDC DeveloperName (`Receipt_vod`).
 */
export function rollupSign(
  objectType: string,
  opts: { transferIn?: boolean } = {},
): 1 | -1 | 0 {
  const t = objectType
    .trim()
    .toLowerCase()
    .replace(/(_vod|__v)$/, "");
  switch (t) {
    case "receipt":
      return 1;
    case "transfer":
      return opts.transferIn ? 1 : -1;
    case "disbursement":
    case "return":
      return -1;
    case "adjustment":
      return 1;
    default:
      return 0;
  }
}

/** `rollupSign(...) * quantity`; `0` for unknown types or non-numeric quantities. */
export function signedQuantity(
  objectType: string,
  quantity: unknown,
  opts: { transferIn?: boolean } = {},
): number {
  const q = typeof quantity === "number" ? quantity : Number(quantity);
  if (!Number.isFinite(q)) return 0;
  return rollupSign(objectType, opts) * q;
}

/**
 * `custom(accountRef)`: `ref(account)` whose requirement is conditional —
 * required on disbursements (`REQUIRED_MISSING`, fatal), optional otherwise.
 * An unresolved account on a disbursement is left to the normal optional
 * path (omitted now, re-pointed by the FK-consistency pass) because the
 * `required` flag of the row is what routes `pending_fk`.
 */
export const accountRef: CustomTransformFn = (
  value,
  row,
  ctx,
): TransformResult => {
  const empty = value === null || value === undefined || value === "";
  if (empty) {
    if (isDisbursement(row))
      return {
        omit: true,
        diagnostic: {
          kind: "required_missing",
          field: ctx.field.target,
          code: "REQUIRED_MISSING",
          detail: "account__v is required on disbursement transactions",
          fatal: true,
        },
      };
    return { omit: true };
  }
  return applyTransform({ kind: "ref", objectKey: "account" }, value, row, ctx);
};


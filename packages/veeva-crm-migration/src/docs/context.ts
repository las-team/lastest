export function totalUsers(profile: ProfileConfig): number {
  return Object.values(profile.activeUsersByCountry).reduce((a, b) => a + b, 0);
}

/** Active users of a profile in a country; the GLOBAL bucket counts every user. */
export function usersIn(profile: ProfileConfig, country: CountryCode): number {
  return country === GLOBAL_COUNTRY
    ? totalUsers(profile)
    : (profile.activeUsersByCountry[country] ?? 0);
}

/** `DE 10, FR 5` sorted by count then code. */
export function usersByCountry(profile: ProfileConfig): string {
  return sorted(
    Object.entries(profile.activeUsersByCountry).filter(([, n]) => n > 0),
    ([, n]) => -n,
    ([c]) => c,
  )
    .map(([c, n]) => `${c} ${n}`)
    .join(", ");
}

/** DESIGN §2.2 / §5.1 disposition column. */
export function disposition(cp: ClassifiedProfile): string {
  if (totalUsers(cp.profile) === 0) return "drop (0 active users)";
  return cp.shared ? "shared" : "keep";
}

/** Languages (`LanguageLocaleKey`) in use in a country, most users first. */
export function languagesOf(ctx: Ctx, country: CountryCode): string[] {
  const langs = ctx.languagesByCountry.get(country);
  if (!langs) return [];
  return sorted(
    [...langs.entries()],
    ([, n]) => -n,
    ([l]) => l,
  ).map(([l]) => l);
}

/** `de` for `de_DE` / `de-DE` / `de`. */
export function langBase(lang: string): string {
  return lang.toLowerCase().split(/[_-]/)[0] ?? "";
}

/** `User_Type_vod__c` values of a set of profiles (country-filtered when the user summary allows). */
export function userTypesOf(
  ctx: Ctx,
  profiles: readonly ClassifiedProfile[],
  country: CountryCode,
): string[] {
  const counts = new Map<string, number>();
  const names = new Set(profiles.map((p) => p.profile.name));
  const ids = new Set(profiles.map((p) => p.profile.id));
  const fromUsers = (ctx.snapshot.users ?? []).filter(
    (u) =>
      (ids.has(u.profileId) || names.has(u.profileName)) &&
      u.userType &&
      (country === GLOBAL_COUNTRY || u.country === country),
  );
  if (fromUsers.length) {
    for (const u of fromUsers)
      counts.set(u.userType!, (counts.get(u.userType!) ?? 0) + u.activeUsers);
  } else {
    for (const p of profiles)
      for (const [t, n] of Object.entries(
        repTypeCountsFor(p.profile, ctx.snapshot.users),
      ))
        counts.set(t, (counts.get(t) ?? 0) + n);
  }
  return sorted(
    [...counts.entries()],
    ([, n]) => -n,
    ([t]) => t,
  ).map(([t, n]) => `${t} (${n})`);
}

/** Countries a VMOC where clause filters on. */
export function vmocCountries(v: VmocConfig): string[] {
  return unique(countriesFromWhereClause(v.whereClause));
}

export function byName<T extends { name: string }>(a: T, b: T): number {
  return cmp(a.name, b.name);
}

export function profilesSorted(
  profiles: readonly ClassifiedProfile[],
): ClassifiedProfile[] {
  return sorted(profiles, (p) => p.profile.name);
}
